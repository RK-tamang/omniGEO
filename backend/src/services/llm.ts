/**
 * LLM API clients for the OmniGEO content engine.
 * OpenAI GPT-4o-mini: drafts GEO blogs & content briefs ($0.15/$0.60 per 1M tokens)
 * Claude 3.5 Haiku: rewrites/modifies content ($0.80/$4.00 per 1M tokens)
 *
 * When API keys are placeholders (e.g. "sk-demo-key") the clients fall back to a
 * deterministic local simulation so the product stays fully usable in dev, and
 * results are always flagged with `simulated: true`.
 */

export interface LLMUsage {
  promptTokens: number;
  completionTokens: number;
  totalTokens: number;
  estimatedCost: number;
}

export interface LLMResult {
  content: string;
  usage: LLMUsage;
  model: string;
  simulated: boolean;
  fallbackReason?: string;
}

export interface GenerateRequest {
  prompt: string;
  systemPrompt?: string;
  model?: "gpt-4o-mini" | "gpt-4o" | "gpt-4-turbo";
  maxTokens?: number;
  temperature?: number;
}

export interface ModifyRequest {
  content: string;
  instruction: string;
  format?: "markdown" | "html" | "json" | "table";
  model?: "claude-3-5-haiku" | "claude-3-5-sonnet";
}

/** True when the key looks like a real credential rather than a dev placeholder. */
export function isLiveCredential(key?: string | null): boolean {
  if (!key) return false;
  const k = key.trim().toLowerCase();
  if (k.length < 12) return false;
  return !k.includes("demo") && !k.includes("your-") && !k.includes("example") && !k.includes("placeholder");
}

const USD_TO_NPR = 132;

const OPENAI_RATES: Record<string, { input: number; output: number }> = {
  "gpt-4o-mini": { input: 0.15 / 1_000_000, output: 0.6 / 1_000_000 },
  "gpt-4o": { input: 2.5 / 1_000_000, output: 10.0 / 1_000_000 },
  "gpt-4-turbo": { input: 10.0 / 1_000_000, output: 30.0 / 1_000_000 },
};

const ANTHROPIC_RATES: Record<string, { input: number; output: number }> = {
  "claude-3-5-haiku-20241022": { input: 0.8 / 1_000_000, output: 4.0 / 1_000_000 },
  "claude-3-5-sonnet-20241022": { input: 3.0 / 1_000_000, output: 15.0 / 1_000_000 },
};

function estimateTokens(text: string): number {
  return Math.max(1, Math.ceil(text.length / 4));
}

function openaiCost(model: string, inputTokens: number, outputTokens: number): number {
  const rate = OPENAI_RATES[model] || OPENAI_RATES["gpt-4o-mini"];
  return inputTokens * rate.input + outputTokens * rate.output;
}

function anthropicCost(model: string, inputTokens: number, outputTokens: number): number {
  const rate = ANTHROPIC_RATES[model] || ANTHROPIC_RATES["claude-3-5-haiku-20241022"];
  return inputTokens * rate.input + outputTokens * rate.output;
}

/** Deterministic dev-mode generation used when no real OpenAI key is configured. */
function simulateGeneration(request: GenerateRequest): LLMResult {
  const model = request.model || "gpt-4o-mini";
  const topic = request.prompt.trim().replace(/\s+/g, " ").slice(0, 180);
  const promptTokens = estimateTokens(request.prompt) + estimateTokens(request.systemPrompt || "");
  const content = [
    `# GEO Content Brief: ${topic}`,
    ``,
    `> Generated by OmniGEO Content Engine (simulated mode - configure OPENAI_API_KEY for live model output).`,
    ``,
    `## Executive Summary`,
    `This brief targets the query intent behind "${topic}". Lead with a direct, extractable answer in the first sentence, support it with 2-3 verifiable statistics, and mirror the exact question phrasing in an H2 so answer engines can lift it verbatim.`,
    ``,
    `## Recommended Structure`,
    `1. **Direct answer block** - 40-60 words, no marketing fluff, quotable by ChatGPT/Perplexity/Gemini.`,
    `2. **Evidence section** - benchmark table with concrete numbers (latency, cost, adoption).`,
    `3. **Entity clarity** - define brand, category, and differentiating attributes in schema-friendly prose.`,
    `4. **FAQ block** - 4-6 Question/Answer pairs marked up with FAQPage JSON-LD.`,
    `5. **Citation hooks** - original data, comparison matrices, and canonical definitions AI engines prefer to cite.`,
    ``,
    `## Target Entities`,
    `- Primary category entity and its attributes`,
    `- Comparison entities (alternatives, competitors, pricing tiers)`,
    `- Compliance/trust entities (SOC 2, uptime SLA, support model)`,
    ``,
    `## Optimization Checklist`,
    `- [x] Question-form H2 headings matching conversational queries`,
    `- [ ] Publish matching FAQPage + TechArticle JSON-LD`,
    `- [ ] Add /llms.txt entry linking to this article`,
    `- [ ] Include one original statistic with a named source`,
    ``,
    `*To enable full model output, set a real OPENAI_API_KEY in backend/.env.*`,
  ].join("\n");

  const completionTokens = estimateTokens(content);

  return {
    content,
    usage: {
      promptTokens,
      completionTokens,
      totalTokens: promptTokens + completionTokens,
      estimatedCost: openaiCost(model, promptTokens, completionTokens),
    },
    model,
    simulated: true,
    fallbackReason: "OPENAI_API_KEY is not configured (placeholder credentials)",
  };
}

/** Deterministic dev-mode modification used when no real Anthropic key is configured. */
function simulateModification(request: ModifyRequest): LLMResult {
  const model = request.model || "claude-3-5-haiku";
  const format = request.format || "markdown";
  const promptTokens = estimateTokens(request.content) + estimateTokens(request.instruction);

  let content: string;
  if (format === "json") {
    content = JSON.stringify(
      {
        instruction: request.instruction,
        originalLength: request.content.length,
        processedContent: request.content.slice(0, 600),
        note: "Simulated output - configure ANTHROPIC_API_KEY for live Claude processing",
      },
      null,
      2
    );
  } else if (format === "table") {
    content = [
      `| Field | Original | After Gap Modifier |`,
      `| --- | --- | --- |`,
      `| Length | ${request.content.length} chars | optimized |`,
      `| Instruction | - | ${request.instruction.replace(/\|/g, "\\|").slice(0, 80)} |`,
      `| Format | raw | ${format} |`,
    ].join("\n");
  } else if (format === "html") {
    content = `<div class="gap-modifier-result"><p>${request.instruction}</p><article>${request.content
      .slice(0, 800)
      .replace(/</g, "&lt;")}</article></div>`;
  } else {
    content = [
      `> **Gap Modifier (simulated):** ${request.instruction}`,
      ``,
      request.content.slice(0, 1200),
      ``,
      `---`,
      `*Simulated response - set ANTHROPIC_API_KEY in backend/.env for live Claude output.*`,
    ].join("\n");
  }

  const completionTokens = estimateTokens(content);

  return {
    content,
    usage: {
      promptTokens,
      completionTokens,
      totalTokens: promptTokens + completionTokens,
      estimatedCost: anthropicCost(model, promptTokens, completionTokens),
    },
    model,
    simulated: true,
    fallbackReason: "ANTHROPIC_API_KEY is not configured (placeholder credentials)",
  };
}

/** OpenAI chat completion. Falls back to simulation on missing/invalid credentials. */
export async function generateContent(request: GenerateRequest): Promise<LLMResult> {
  const model = request.model || "gpt-4o-mini";
  const apiKey = process.env.OPENAI_API_KEY;
  const baseUrl = process.env.OPENAI_BASE_URL || "https://api.openai.com/v1";

  if (!isLiveCredential(apiKey)) {
    return simulateGeneration(request);
  }

  try {
    const response = await fetch(`${baseUrl}/chat/completions`, {
      method: "POST",
      headers: {
        Authorization: `Bearer ${apiKey}`,
        "Content-Type": "application/json",
      },
      body: JSON.stringify({
        model,
        messages: [
          { role: "system", content: request.systemPrompt || "You are an expert GEO content strategist." },
          { role: "user", content: request.prompt },
        ],
        temperature: request.temperature ?? 0.7,
        max_tokens: request.maxTokens ?? 4000,
      }),
      signal: AbortSignal.timeout(60_000),
    });

    if (!response.ok) {
      const errBody = await response.text().catch(() => "");
      let message = `OpenAI API error ${response.status}`;
      try {
        message = JSON.parse(errBody)?.error?.message || message;
      } catch {
        /* keep default message */
      }
      const fallback = simulateGeneration(request);
      return { ...fallback, fallbackReason: `Live OpenAI call failed: ${message}` };
    }

    const data = (await response.json()) as {
      choices: Array<{ message: { content: string } }>;
      usage: { prompt_tokens: number; completion_tokens: number; total_tokens: number };
    };
    const usage = data.usage;

    return {
      content: data.choices[0].message.content,
      usage: {
        promptTokens: usage.prompt_tokens,
        completionTokens: usage.completion_tokens,
        totalTokens: usage.total_tokens,
        estimatedCost: openaiCost(model, usage.prompt_tokens, usage.completion_tokens),
      },
      model,
      simulated: false,
    };
  } catch (error: any) {
    const fallback = simulateGeneration(request);
    return { ...fallback, fallbackReason: `Live OpenAI call failed: ${error?.message || "network error"}` };
  }
}

/** Anthropic message completion. Falls back to simulation on missing/invalid credentials. */
export async function modifyContent(request: ModifyRequest): Promise<LLMResult> {
  const model = request.model || "claude-3-5-haiku-20241022";
  const apiKey = process.env.ANTHROPIC_API_KEY;
  const baseUrl = process.env.ANTHROPIC_BASE_URL || "https://api.anthropic.com/v1";

  if (!isLiveCredential(apiKey)) {
    return simulateModification(request);
  }

  const formatInstruction =
    request.format === "table"
      ? "Format output as a clean Markdown table with headers."
      : request.format === "json"
      ? "Output only valid JSON. No explanations."
      : request.format === "html"
      ? "Output clean, semantic HTML."
      : "Output clean Markdown.";

  try {
    const response = await fetch(`${baseUrl}/messages`, {
      method: "POST",
      headers: {
        "x-api-key": String(apiKey),
        "anthropic-version": "2023-06-01",
        "Content-Type": "application/json",
      },
      body: JSON.stringify({
        model,
        system: `You are an expert content editor. ${formatInstruction}`,
        messages: [
          { role: "user", content: `Content:\n${request.content}\n\nInstruction: ${request.instruction}` },
        ],
        max_tokens: 8000,
        temperature: 0.3,
      }),
      signal: AbortSignal.timeout(60_000),
    });

    if (!response.ok) {
      const errBody = await response.text().catch(() => "");
      let message = `Anthropic API error ${response.status}`;
      try {
        message = JSON.parse(errBody)?.error?.message || message;
      } catch {
        /* keep default message */
      }
      const fallback = simulateModification(request);
      return { ...fallback, fallbackReason: `Live Anthropic call failed: ${message}` };
    }

    const data = (await response.json()) as {
      content: Array<{ text: string }>;
      usage: { input_tokens: number; output_tokens: number };
    };
    const usage = data.usage;

    return {
      content: data.content[0].text,
      usage: {
        promptTokens: usage.input_tokens,
        completionTokens: usage.output_tokens,
        totalTokens: usage.input_tokens + usage.output_tokens,
        estimatedCost: anthropicCost(model, usage.input_tokens, usage.output_tokens),
      },
      model,
      simulated: false,
    };
  } catch (error: any) {
    const fallback = simulateModification(request);
    return { ...fallback, fallbackReason: `Live Anthropic call failed: ${error?.message || "network error"}` };
  }
}

/** Convert USD cost to NPR using the project-wide rate. */
export function usdToNpr(usd: number): number {
  return Math.round(usd * USD_TO_NPR * 100) / 100;
}
